import { describe, expect, it, vi } from "vitest";

vi.hoisted(() => {
  for (const t of ["CORE", "LEDGER", "COMMERCE", "CONTENT", "OPS", "IMPORT", "SOL"]) process.env[`PLEXO_${t}_TABLE`] = `test-${t.toLowerCase()}`;
});

// The SDK refuses a non-streaming request whose max_tokens could take over 10 minutes —
// the mocked create() throws exactly that, so only a streamed call can succeed.
vi.mock("@anthropic-ai/sdk", () => ({
  default: class {
    messages = {
      create: vi.fn(async () => {
        throw new Error("Streaming is required for operations that may take longer than 10 minutes.");
      }),
      stream: vi.fn(() => ({
        finalMessage: async () => ({ content: [{ type: "text", text: "<html>coffee</html>" }], usage: { input_tokens: 10, output_tokens: 20 }, stop_reason: "end_turn" }),
      })),
    };
  },
}));

import { generate } from "@/lib/ai/providers/anthropic";
import { aiErrorMessage } from "@/lib/ai/requestErrors";

describe("AI generation", () => {
  it("a large page (32,000 output tokens) is generated by streaming, not refused", async () => {
    const out = await generate({ model: "claude-haiku-4-5", apiKey: "k", systemPrompt: "s", userPrompt: "A modern landing page for a coffee shop", maxTokens: 32000 });
    expect(out).toEqual({ text: "<html>coffee</html>", usage: { inputTokens: 10, outputTokens: 20 }, truncated: false });
  });

  it("provider failures read as what happened and what to do — never the SDK's wording", async () => {
    const { friendlyProviderError } = await import("@/lib/ai/providerErrors");
    expect(friendlyProviderError({ status: 401, message: "invalid x-api-key" })).toMatch(/rejected this account's API key/);
    expect(friendlyProviderError({ status: 429, message: "rate_limit_error" })).toMatch(/rate-limiting/);
    expect(friendlyProviderError({ status: 529, message: "Overloaded" })).toMatch(/very busy/);
    expect(friendlyProviderError(new Error("Request timed out."))).toMatch(/didn't respond in time/);
    expect(friendlyProviderError(new Error("Streaming is required for operations that may take longer than 10 minutes"))).not.toMatch(/Streaming/);
  });

  it("the dashboard explains a gateway timeout and keeps the server's own message", () => {
    expect(aiErrorMessage(504, null)).toMatch(/longer than we can wait/);
    expect(aiErrorMessage(502, {})).toMatch(/longer than we can wait/);
    expect(aiErrorMessage(500, { error: "The AI service is very busy right now. Try again in a minute." })).toBe("The AI service is very busy right now. Try again in a minute.");
    expect(aiErrorMessage(402, {})).toMatch(/out of AI credits/);
  });
});
