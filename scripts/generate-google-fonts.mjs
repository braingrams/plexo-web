// Generates lib/fonts/googleFontsData.ts: every Google Fonts family the brand font picker offers, with its style group, its
// popularity rank, the weights it really has and whether it has italics. No network is needed at runtime: re-run this to refresh.
//
//   node scripts/generate-google-fonts.mjs [path/to/metadata.json]
//
// Source: the file given, otherwise Google's open font metadata at https://fonts.google.com/metadata/fonts (no key needed; it has
// categories, popularity and every weight, which the Developer API does not list for variable fonts).
import { readFileSync, writeFileSync } from "node:fs";

const CAT = { "Sans Serif": "s", Serif: "f", Display: "d", Monospace: "m", Handwriting: "h" };
const meta = process.argv[2] ? JSON.parse(readFileSync(process.argv[2], "utf8")) : await (await fetch("https://fonts.google.com/metadata/fonts")).json();

// Only families that load by their plain name and have Latin letters (the picker is for Latin-script sites; a name with
// punctuation can't safely go in a URL or a stylesheet). The Noto families for other writing systems are left out: they would only crowd a Latin-script list.
const list = meta.familyMetadataList.filter((f) => f.subsets?.includes("latin") && CAT[f.category] && !/^Noto (Sans|Serif) \w+/.test(f.family) && f.family !== "Google Sans" && /^[A-Za-z0-9][A-Za-z0-9 ]{0,63}$/.test(f.family) && Object.keys(f.fonts).some((k) => /^[1-9]00i?$/.test(k)));
const rows = list
  .sort((a, b) => a.popularity - b.popularity)
  .map((f) => {
    const keys = Object.keys(f.fonts);
    const weights = [...new Set(keys.filter((k) => /^[1-9]00i?$/.test(k)).map((k) => Number(k.slice(0, 3)) / 100))].sort((a, b) => a - b).join("");
    const italic = keys.some((k) => /^[1-9]00i$/.test(k)) ? "i" : "";
    return `${f.family}|${CAT[f.category]}|${weights}|${italic}`;
  });

writeFileSync(
  new URL("../lib/fonts/googleFontsData.ts", import.meta.url),
  `// GENERATED by scripts/generate-google-fonts.mjs from Google's font metadata. Do not edit by hand.
// "Family|group|weights|italic", most used first (the position is the popularity rank). Groups: s sans, f serif, d display, m mono, h handwriting.
// Weights are hundreds ("47" = 400 and 700). The last field is "i" when the family has italics.
export const GOOGLE_FONTS_DATA: string[] = ${JSON.stringify(rows)};
`,
);
console.log("families", rows.length);
